/**
 * PDF Export using native browser print functionality.
 * 
 * Creates an iframe-based document view and triggers the browser's
 * print dialog, allowing users to save as PDF with zero dependencies.
 */

export async function exportAsPDF(title: string, draft: string, options = {}) {
  const {
    paperSize = 'A4',
    margins = { top: 20, bottom: 20, left: 20, right: 20 },
    fontScale = 1,
  } = typeof options === 'object' ? options : {};

  // Create unique iframe ID to avoid conflicts
  const iframeId = `pdf-preview-${Date.now()}`;

  // Generate formatted HTML for printing
  const htmlContent = `
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${title}</title>
  <style>
    @page {
      size: ${paperSize};
      margin-top: ${margins.top}mm;
      margin-bottom: ${margins.bottom}mm;
      margin-left: ${margins.left}mm;
      margin-right: ${margins.right}mm;
    }
    body {
      font-family: Georgia, serif;
      line-height: 1.6;
      font-size: 11pt;
      max-width: 90%;
      margin: 0 auto;
      padding: 20px;
    }
    h1 {
      font-size: 24pt;
      margin-bottom: 10px;
      color: #1a1a1a;
    }
    .metadata {
      font-size: 8pt;
      color: #666;
      margin-bottom: 30px;
      border-bottom: 1px solid #ddd;
      padding-bottom: 5px;
    }
    .draft-content {
      white-space: pre-wrap;
      word-wrap: break-word;
    }
    @media print {
      body { padding: 0; }
      .no-print { display: none; }
    }
  </style>
</head>
<body>
  <h1>${escapeHtml(title)}</h1>
  <div class="metadata">
    Generated by Draftwise on ${new Date().toLocaleDateString()}
  </div>
  <div class="draft-content">${escapeHtml(draft)}</div>
  
  <script>
    // Auto-trigger print when page loads
    window.onload = function() {
      setTimeout(function() {
        window.print();
      }, 250);
    };
  </script>
</body>
</html>`;

  return new Promise((resolve, reject) => {
    try {
      // Create iframe to render content
      const iframe = document.createElement('iframe');
      iframe.id = iframeId;
      iframe.style.position = 'fixed';
      iframe.style.top = '-9999px';
      iframe.style.width = '1px';
      iframe.style.height = '1px';
      iframe.style.border = 'none';
      
      document.body.appendChild(iframe);

      // Write content to iframe
      const iframeDoc = (iframe.contentWindow || iframe.contentDocument?.document).document;
      iframeDoc.open();
      iframeDoc.write(htmlContent);
      iframeDoc.close();

      // Clean up iframe after print dialog closes
      iframe.onload = () => {
        setTimeout(() => {
          document.body.removeChild(iframe);
        }, 1000);
      };

      resolve({ success: true });
    } catch (error) {
      console.error('PDF export failed:', error);
      reject(error);
    }
  });
}

/**
 * Escape HTML special characters to prevent XSS.
 */
function escapeHtml(text: string): string {
  const map: Record<string, string> = {
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#039;',
  };
  return text.replace(/[&<>"']/g, (m) => map[m]);
}
